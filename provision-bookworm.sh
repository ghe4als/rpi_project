#!/bin/bash
# Bookworm variant of provision.sh.
#
# Raspberry Pi OS Bookworm Lite has NO cloud-init. The canonical headless
# provisioning mechanism is a firstrun.sh script invoked via a
# systemd.run= hook appended to cmdline.txt (the same thing rpi-imager does).
#
# This script:
#   - renders a firstrun.sh onto bootfs from .env
#   - appends the systemd.run= hook to cmdline.txt (idempotent)
#   - stages the role tree at /boot/firmware/role (same layout as Trixie path)
#   - records a pending flash to inventory.yaml
#
# firstrun.sh on first boot: sets hostname (serial-derived), creates user,
# enables ssh, deploys SSH key, joins wifi, installs+enables role-setup.service,
# then deletes itself.
#
# Usage: ./provision-bookworm.sh [ROLE] [/Volumes/bootfs]
set -euo pipefail

REPO="$(cd "$(dirname "$0")" && pwd)"

ROLE_ARG=""
BOOT=""
for arg in "$@"; do
  if [[ "$arg" == /* ]]; then BOOT="$arg"; else ROLE_ARG="$arg"; fi
done
BOOT="${BOOT:-/Volumes/bootfs}"

[[ -f "$REPO/.env" ]] || { echo "ERROR: $REPO/.env missing." >&2; exit 1; }
[[ -d "$BOOT" ]] || { echo "ERROR: $BOOT not mounted. Re-insert SD card." >&2; exit 1; }

# shellcheck disable=SC1091
set -a; source "$REPO/.env"; set +a
: "${WIFI_SSID:?}" "${WIFI_PSK:?}" "${WIFI_COUNTRY:?}" \
  "${PI_USERNAME:?}" "${PI_PASSWORD:?}" "${TIMEZONE:?}" "${LOCALE:?}" "${KEYMAP:?}"

ROLE="${ROLE_ARG:-${ROLE:-base}}"
# ROLES_PATHS: colon-separated list of dirs to search for <role>/install.sh.
# Defaults to $REPO/roles (backwards-compatible). External sibling repos can
# extend this, e.g. ROLES_PATHS=/path/to/piChick/roles:./roles ./provision-bookworm.sh chicken-cam ...
ROLES_PATHS="${ROLES_PATHS:-$REPO/roles}"
ROLE_SRC=""
for _path in ${ROLES_PATHS//:/ }; do
  if [[ -x "$_path/$ROLE/install.sh" ]]; then
    ROLE_SRC="$_path/$ROLE"
    break
  fi
done
if [[ -z "$ROLE_SRC" ]]; then
  echo "ERROR: role '$ROLE' not found in ROLES_PATHS='$ROLES_PATHS' (looked for <path>/$ROLE/install.sh)" >&2
  exit 1
fi
echo "Selected role: $ROLE (Bookworm/firstrun.sh path)"

PI_PASSWORD_HASH=$(openssl passwd -6 "$PI_PASSWORD")

# Collect SSH public keys.
SSH_KEYS_DIR="${SSH_KEYS_DIR:-$HOME/.ssh}"
SSH_PUBKEY=""
for keyfile in "$SSH_KEYS_DIR"/id_ed25519.pub "$SSH_KEYS_DIR"/id_rsa.pub "$SSH_KEYS_DIR"/id_ecdsa.pub; do
  [[ -f "$keyfile" ]] || continue
  SSH_PUBKEY="$(head -n1 "$keyfile")"
  break
done
[[ -n "$SSH_PUBKEY" ]] && echo "Embedding SSH key from $SSH_KEYS_DIR" || echo "WARNING: no SSH pubkey found"

# -----------------------------------------------------------------------------
# Stage role tree (identical layout to Trixie path so install.sh is reused).
# -----------------------------------------------------------------------------
echo "Staging role '$ROLE' (+ base) onto bootfs"
rm -rf "$BOOT/role"
mkdir -p "$BOOT/role"
COPYFILE_DISABLE=1 cp -R "$REPO/roles/base"   "$BOOT/role/base"
if [[ "$ROLE" != "base" ]]; then
  COPYFILE_DISABLE=1 cp -R "$ROLE_SRC"        "$BOOT/role/$ROLE"
  COPYFILE_DISABLE=1 cp "$ROLE_SRC/install.sh" "$BOOT/role/install.sh"
else
  COPYFILE_DISABLE=1 cp "$REPO/roles/base/install.sh" "$BOOT/role/install.sh"
fi
find "$BOOT/role" -name install.sh -exec chmod +x {} \;

# role.env for the touchscreen role (KeDei params live here).
ROLE_ENV_FILE="$BOOT/role/role.env"
{
  echo "ROLE=$ROLE"
  for var in $(env | awk -F= '/^(TOUCHSCREEN|NATS|OLLAMA|COOP|MOTION)_/ {print $1}'); do
    printf '%s=%q\n' "$var" "${!var}"
  done
} > "$ROLE_ENV_FILE"

COPYFILE_DISABLE=1 cp "$REPO/role-setup.service.tmpl" "$BOOT/role-setup.service"

# -----------------------------------------------------------------------------
# Render firstrun.sh.
# -----------------------------------------------------------------------------
echo "Writing firstrun.sh"
cat > "$BOOT/firstrun.sh" <<FIRSTRUN
#!/bin/bash
set +e
# Bookworm first-boot provisioning. Auto-generated by provision-bookworm.sh.
# Runs in the minimal kernel-command-line.target (NO multi-user services).
# Log everything to bootfs so failures are diagnosable from a Mac.
exec > /boot/firmware/firstrun.log 2>&1
echo "[firstrun] start \$(date)"

# Hostname from CPU serial (matches Trixie path's rpi-<6hex> convention).
SERIAL=\$(awk '/^Serial/ {print \$3}' /proc/cpuinfo)
SUFFIX=\$(echo "\${SERIAL:-unknown}" | tail -c 7)
NEW_HOST="rpi-\${SUFFIX}"
if [ -f /usr/lib/raspberrypi-sys-mods/imager_custom ]; then
  /usr/lib/raspberrypi-sys-mods/imager_custom set_hostname "\$NEW_HOST"
else
  echo "\$NEW_HOST" > /etc/hostname
  hostnamectl set-hostname "\$NEW_HOST" 2>/dev/null
  sed -i "s/^127.0.1.1.*/127.0.1.1\t\$NEW_HOST/" /etc/hosts 2>/dev/null || echo -e "127.0.1.1\t\$NEW_HOST" >> /etc/hosts
fi

# Enable SSH.
if [ -f /usr/lib/raspberrypi-sys-mods/imager_custom ]; then
  /usr/lib/raspberrypi-sys-mods/imager_custom enable_ssh
else
  systemctl enable ssh
fi

# Create user + password.
if [ -f /usr/lib/userconf-pi/userconf ]; then
  /usr/lib/userconf-pi/userconf "$PI_USERNAME" '$PI_PASSWORD_HASH'
fi

# SSH public key.
USERHOME="/home/$PI_USERNAME"
if [ -n "$SSH_PUBKEY" ] && [ -d "\$USERHOME" ]; then
  mkdir -p "\$USERHOME/.ssh"
  chmod 700 "\$USERHOME/.ssh"
  echo "$SSH_PUBKEY" >> "\$USERHOME/.ssh/authorized_keys"
  chown -R "$PI_USERNAME:$PI_USERNAME" "\$USERHOME/.ssh"
  chmod 600 "\$USERHOME/.ssh/authorized_keys"
fi

# WiFi (Bookworm uses NetworkManager via imager_custom set_wlan).
# No -h flag: Brook is a broadcast SSID, not hidden.
# Set the regulatory country FIRST (file-based, not raspi-config which is risky
# in early boot) and clear the rfkill soft-block - on a Pi the wlan0 radio stays
# soft-blocked until the country is known, so set_wlan alone can silently fail
# to associate (this bit us on the Trixie attempt). The cfg80211 regdom is also
# set via cmdline as a backup.
echo "[firstrun] setting wifi country + unblocking radio"
echo "REGDOMAIN=$WIFI_COUNTRY" > /etc/default/crda 2>/dev/null
iw reg set "$WIFI_COUNTRY" 2>/dev/null
rfkill unblock wifi 2>/dev/null
if [ -f /usr/lib/raspberrypi-sys-mods/imager_custom ]; then
  /usr/lib/raspberrypi-sys-mods/imager_custom set_wlan "$WIFI_SSID" "$WIFI_PSK" "$WIFI_COUNTRY"
fi
# Belt-and-suspenders: also write a NetworkManager keyfile directly, in case
# set_wlan's helper misbehaves on this image. NM auto-loads system-connections.
mkdir -p /etc/NetworkManager/system-connections
cat > /etc/NetworkManager/system-connections/"$WIFI_SSID".nmconnection <<NMCONN
[connection]
id=$WIFI_SSID
type=wifi
autoconnect=true
[wifi]
mode=infrastructure
ssid=$WIFI_SSID
[wifi-security]
key-mgmt=wpa-psk
psk=$WIFI_PSK
[ipv4]
method=auto
[ipv6]
method=auto
NMCONN
chmod 600 /etc/NetworkManager/system-connections/"$WIFI_SSID".nmconnection

# Locale / timezone / keymap: do NOT run raspi-config here. In the minimal
# kernel-command-line.target environment, do_change_locale triggers
# dpkg-reconfigure which can hang/fail (it hung this Pi's first boot). Write
# the values directly; raspi-config-equivalent files are applied by normal
# boot services afterwards.
echo "[firstrun] setting timezone/locale/keymap (file-based, no raspi-config)"
ln -sf "/usr/share/zoneinfo/$TIMEZONE" /etc/localtime 2>/dev/null
echo "$TIMEZONE" > /etc/timezone
echo "LANG=$LOCALE" > /etc/default/locale
echo "$LOCALE UTF-8" > /etc/locale.gen

# Install + enable the role-setup service (runs the role install on next boot,
# in full multi-user.target where apt/locale/etc. all work).
echo "[firstrun] installing role-setup.service"
if [ -f /boot/firmware/role-setup.service ]; then
  install -m 0644 /boot/firmware/role-setup.service /etc/systemd/system/role-setup.service
elif [ -f /boot/role-setup.service ]; then
  install -m 0644 /boot/role-setup.service /etc/systemd/system/role-setup.service
fi
systemctl enable role-setup.service

# CRITICAL: strip the systemd.run hook from cmdline.txt BEFORE the success
# reboot, exactly as the official rpi-imager firstrun.sh does. Without this,
# the next boot re-enters kernel-command-line.target with a now-missing
# firstrun.sh and hangs before networking/ssh ever start (this killed the
# previous boot). Then remove self.
echo "[firstrun] cleaning cmdline.txt hook + removing self"
sed -i 's| systemd.run.*||g' /boot/firmware/cmdline.txt 2>/dev/null
sed -i 's| systemd.run.*||g' /boot/cmdline.txt 2>/dev/null
echo "[firstrun] done \$(date)"
rm -f /boot/firmware/firstrun.sh /boot/firstrun.sh
exit 0
FIRSTRUN
chmod +x "$BOOT/firstrun.sh"

# -----------------------------------------------------------------------------
# Append systemd.run hook to cmdline.txt (idempotent).
# -----------------------------------------------------------------------------
CMDLINE="$BOOT/cmdline.txt"
HOOK="systemd.run=/boot/firmware/firstrun.sh systemd.run_success_action=reboot systemd.unit=kernel-command-line.target"
if ! grep -q "firstrun.sh" "$CMDLINE"; then
  cp "$CMDLINE" "$CMDLINE.orig"
  sed -i.bak "s|\$| $HOOK|" "$CMDLINE"
  rm -f "$CMDLINE.bak"
  echo "Appended firstrun hook to cmdline.txt"
else
  echo "cmdline.txt already has firstrun hook"
fi

# -----------------------------------------------------------------------------
# Remove the stale Trixie cloud-init files (they'd be ignored, but clean up).
# -----------------------------------------------------------------------------
rm -f "$BOOT/user-data" "$BOOT/network-config" "$BOOT/meta-data"

# Record pending flash to inventory.
if command -v yq >/dev/null 2>&1; then
  INV="$REPO/inventory.yaml"
  [[ -f "$INV" ]] || printf '%s\n' '{}' > "$INV"
  TS="$(date +%Y-%m-%dT%H:%M:%S%z | sed 's/\([+-][0-9][0-9]\)\([0-9][0-9]\)$/\1:\2/')"
  yq -i ".pending_flashes += [{
    \"flashed_at\": \"$TS\", \"image\": \"bookworm-armhf-lite\", \"role\": \"$ROLE\",
    \"pi_username\": \"$PI_USERNAME\", \"wifi_ssid\": \"$WIFI_SSID\", \"os\": \"bookworm\"
  }]" "$INV"
  echo "[inventory] recorded pending Bookworm flash (role=$ROLE)"
fi

# Cleanup macOS metadata.
find "$BOOT" \( -name '._*' -o -name '.DS_Store' -o -name '.Spotlight-V100' -o -name '.Trashes' -o -name '.fseventsd' \) -exec rm -rf {} + 2>/dev/null || true

sync
echo
echo "Provisioning written to $BOOT. Ejecting..."
PARENT_DISK="$(df "$BOOT" 2>/dev/null | awk 'NR==2{print $1}' | sed 's/s[0-9]*$//')"
if diskutil eject "$BOOT" >/dev/null 2>&1; then
  echo "Ejected. Safe to remove."
elif [[ -n "$PARENT_DISK" ]] && diskutil eject "$PARENT_DISK" >/dev/null 2>&1; then
  echo "Ejected ($PARENT_DISK). Safe to remove."
else
  echo "Eject failed; run 'diskutil eject $PARENT_DISK' manually."
fi
